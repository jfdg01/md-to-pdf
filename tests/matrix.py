"""The test matrix: 5 documents that together try every pair of options that
interact in the code. Checks the coverage, writes tests/a1.md … a5.md from
tests/body.md, and builds their PDFs. Run: uv run python tests/matrix.py
See docs/testing.md."""
import re
import sys
from itertools import combinations, product
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "src"))
import md_to_pdf as m  # noqa: E402

# Factor: (label, front matter for level 0 = default, front matter for level 1).
FACTORS = {
    "P": ("cover",        {"logo": "../assets/img/logo_uja.webp"}, {"cover": "false"}),
    "T": ("toc",          {}, {"toc": "false"}),
    "L": ("lists",        {}, {k: "false" for k in ("figure_index", "table_index",
                                                    "code_index", "acronym_index")}),
    "S": ("page_break",   {}, {"page_break": "true"}),
    "B": ("base level",   {}, {}),  # level 1: the body's headings move up to `#`
    "N": ("numbering",    {}, {"numbering": "false"}),
    "C": ("caption",      {}, {"caption_position": "top"}),
    "I": ("locale",       {"locale": "es"}, {"locale": "en"}),
    "R": ("bibliography", {}, {"bibliography": "test_thesis.bib"}),
    "G": ("page",         {}, {"page_size": "a5", "orientation": "landscape",
                               "margins": "1.5cm"}),
    "D": ("toc_depth",    {"toc_depth": "4"}, {"toc_depth": "5"}),
    "K": ("code_theme",   {}, {"code_theme": "monokai"}),
    "E": (".theme",       {}, {"theme": "sample.theme"}),
}

# Pairs of factors that the same code reads, so all 4 combinations matter.
EDGES = [
    ("P", "T"), ("P", "L"), ("T", "L"),  # what opens page 1
    ("P", "S"), ("T", "S"), ("L", "S"),  # a page break right after it
    ("P", "I"),                          # "By" on the cover or the title block
    ("P", "G"),                          # the cover's page size
    ("P", "E"),                          # title_size… from the theme
    ("T", "D"), ("B", "D"), ("T", "B"),  # the TOC tree and the PDF outline
    ("N", "B"), ("S", "B"), ("N", "T"),  # section numbers, the break per section
    ("R", "I"), ("R", "N"), ("R", "B"), ("R", "T"),  # the references section
    ("E", "K"),                          # theme < front matter precedence
]

# A graph colouring: factors of one colour never share an edge, so they share a
# column. The 4 columns are qualitatively independent: every pair of them holds
# 00, 01, 10 and 11.
COLOUR = {"P": 0, "B": 0, "K": 0, "C": 0, "T": 1, "I": 1, "G": 1, "E": 1,
          "L": 2, "D": 2, "N": 2, "S": 3, "R": 3}
COLUMNS = ["00111", "01011", "01101", "01110"]
ROWS = [{f: int(COLUMNS[COLOUR[f]][r]) for f in FACTORS} for r in range(5)]

ALL_PAIRS = set(product((0, 1), repeat=2))


def check():
    assert all(COLOUR[a] != COLOUR[b] for a, b in EDGES), "bad colouring"
    for a, b in EDGES:
        assert {(r[a], r[b]) for r in ROWS} == ALL_PAIRS, (a, b)
    # Lower bound: P, T, L, S are a clique, and no 4 rows give 4 binary columns
    # with every pair.
    cols = list(product((0, 1), repeat=4))
    assert not any(all({(c[i][r], c[j][r]) for r in range(4)} == ALL_PAIRS
                       for i, j in combinations(range(4), 2))
                   for c in product(cols, repeat=4)), "4 documents would do"


def move_up(md):
    """Drop one `#` from each heading outside code fences."""
    out, fence = [], False
    for line in md.splitlines():
        fence ^= line.startswith("```")
        out.append(line[1:] if not fence and re.match(r"##+ ", line) else line)
    return "\n".join(out) + "\n"


def document(row):
    meta = {"title": "Matriz de pruebas", "subtitle": "Subtítulo",
            "comment": "Comentario", "author": "Autor"}
    for f, (_, off, on) in FACTORS.items():
        meta.update(on if row[f] else off)
    body = (HERE / "body.md").read_text(encoding="utf-8")
    if row["B"]:
        body = move_up(body)
    if not row["R"]:
        body = re.sub(r" ?\[@[^\]]+\]", "", body)
    levels = ", ".join(f"{label} {row[f]}" for f, (label, _, _) in FACTORS.items())
    front = "".join(f"{k}: {v}\n" for k, v in meta.items())
    return f"---\n{front}---\n\n<!-- Generated by tests/matrix.py: {levels} -->\n\n{body}"


if __name__ == "__main__":
    check()
    ok = True
    for i, row in enumerate(ROWS, 1):
        path = HERE / f"a{i}.md"
        path.write_text(document(row), encoding="utf-8")
        ok &= m.convert_and_report(path)
    sys.exit(0 if ok else 1)
